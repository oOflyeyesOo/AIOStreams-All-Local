"""Generate the paste-and-deploy stack from the source stack (requires PyYAML)."""
from pathlib import Path
import sys
import yaml

ROOT = Path(__file__).resolve().parents[1]
PACKAGED = {
    'portal': 'portal', 'controller': 'controller', 'aiostreams': 'aiostreams',
    'sootio': 'sootio', 'anime-kitsu': 'kitsu', 'stremio-web': 'stremio-web',
    'stack-bootstrap': 'bootstrap', 'stack-check': 'bootstrap', 'init-postgres': 'postgres-init',
}


def generate(source):
    source.pop('x-runtime-defaults', None)
    volumes = {'aio-config': {}, 'control-socket': {}}
    for name, service in source['services'].items():
        service.pop('container_name', None)
        service.pop('build', None)
        # The manager installation includes all integrations without profile setup.
        if name != 'stack-check':
            service.pop('profiles', None)
        if name in PACKAGED:
            service['image'] = '${AIO_IMAGE_PREFIX:-ghcr.io/ooflyeyesoo/aio-local}-' + PACKAGED[name] + ':${AIO_IMAGE_TAG:-latest}'
        mounts = []
        for original in service.get('volumes', []):
            host, target, *flags = original.split(':')
            if host.startswith('./data/'):
                volume = host.removeprefix('./data/').replace('/', '-') + '-data'
                volumes[volume] = {}
                mounts.append(':'.join([volume, target, *flags]))
            elif original.startswith('${DOCKER_SOCKET:'):
                mounts.append(original)
            elif host == 'control-socket':
                mounts.append(original)
            elif host == './':
                mounts.append(':'.join(['aio-config', target, *flags]))
            # Everything else is code supplied by a packaged image.
        service['volumes'] = mounts
    portal = source['services']['portal']
    portal.pop('depends_on', None)
    portal.pop('command', None)
    portal['ports'] = ['${PORT_PORTAL:-8088}:8088']
    portal['volumes'].append('aiostreams-data:/app/data/aiostreams:ro')
    portal['environment'] += [
        'AIO_IMAGE_TAG=${AIO_IMAGE_TAG:-latest}',
        'AIO_IMAGE_PREFIX=${AIO_IMAGE_PREFIX:-ghcr.io/ooflyeyesoo/aio-local}',
        'PORT_PORTAL=${PORT_PORTAL:-8088}',
        'INTERNAL_BIND_IP=${INTERNAL_BIND_IP:-127.0.0.1}',
        'DOCKER_SOCKET=${DOCKER_SOCKET:-/var/run/docker.sock}',
    ]
    controller = source['services']['controller']
    controller['environment'].append('AIO_COMPOSE_FILE=compose.manager.yml')
    controller['depends_on'] = {'portal': {'condition': 'service_healthy'}}
    source['services']['stack-bootstrap']['depends_on'].append('controller')
    source['volumes'] = volumes
    return source


class Dumper(yaml.SafeDumper):
    def ignore_aliases(self, data):
        return True


def main():
    config = generate(yaml.safe_load((ROOT / 'docker-compose.yml').read_text()))
    text = '# Generated by scripts/generate_manager_compose.py. See DEPLOYMENT.md.\n'
    text += '# Paste this entire file into a Docker Compose stack editor.\n'
    text += yaml.dump(config, Dumper=Dumper, sort_keys=False, width=120)
    target = ROOT / 'compose.manager.yml'
    if '--check' in sys.argv:
        if not target.exists() or target.read_text() != text:
            raise SystemExit('compose.manager.yml is stale; regenerate it')
    else:
        target.write_text(text, encoding='utf-8', newline='\n')


if __name__ == '__main__':
    main()
